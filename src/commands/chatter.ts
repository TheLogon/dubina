function triggerMatches(needle: string, trigger: string): boolean {
  const t = normalizePhrase(trigger);
  if (!t || !needle) return false;
  
  if (t.length <= 3) {
    if (needle === t) return true;
    return (
      needle.startsWith(`${t} `) ||
      needle.endsWith(` ${t}`) ||
      needle.includes(` ${t} `)
    );
  }
  return needle === t || needle.includes(t);
}

export function findChatterReply(spoken: string): string | null {
  const needle = normalizePhrase(spoken);
  if (!needle) return null;

  let bestLen = -1;
  let bestReplies: string[] | null = null;

  for (const rule of RULES) {
    for (const trigger of rule.triggers) {
      const t = normalizePhrase(trigger);
      if (!triggerMatches(needle, trigger)) continue;
      if (t.length > bestLen) {
        bestLen = t.length;
        bestReplies = rule.replies;
      }
    }
  }

  if (!bestReplies?.length) return null;
  return bestReplies[Math.floor(Math.random() * bestReplies.length)] ?? null;
}

export function allChatterReplies(): string[] {
  const set = new Set<string>();
  for (const rule of RULES) {
    for (const r of rule.replies) set.add(r);
  }
  return [...set];
}
